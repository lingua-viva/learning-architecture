"""Build the SYNTHETIC detection corpus — Phase 0B.4 of
SPEC_LV_UNIFIED_REAL_DATA_FIX_2026-08-19.

Generates ``tests/fixtures/docpipe/synthetic-corpus/`` — a committed,
synthetic-name mirror of the four structural shapes in the REAL corpus
(which lives outside the repo and is never committed). CI scores the
detection pipeline against this mirror via the corpus tests; the real
numbers come from running the same scorer locally against the real files.

The generator is deterministic (fixed names, no randomness) so the
committed fixtures can be regenerated byte-comparably at any time:

    python3 scripts/build_synthetic_corpus.py

Shapes mirrored (structure faithful, names synthetic):
1. grade_sheet_class_list — row 1: class names heading column PAIRS
   (Last|First), row 2: teacher names, rows 3+: Last/First per column
   pair, plus "1/2 groups ..." scheduling-note rows that are NOT students.
2. single_sheet_support — literal "Student"/"class" headers, abbreviated
   names ("First L-W" style), a target class "V".
3. per_class_sheet_support — class code in row 1, a staff first-name
   block ABOVE an "Accommodations ... / Medical needs ..." header row,
   students below it. Staff must never be detected as students.
4. curriculum_mapping + cycle_calendar — ZERO students; packed with the
   non-English capitalized bigrams that produced the false positives.
"""
