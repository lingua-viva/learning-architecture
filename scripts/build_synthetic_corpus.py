def _build_class_list(path: Path) -> list[str]:
    import openpyxl

    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    expected: list[str] = []
    for grade, classes in CLASS_LIST.items():
        ws = wb.create_sheet(title=grade)
        col = 1
        for class_name, info in classes.items():
            ws.cell(row=1, column=col, value=class_name)
            ws.cell(row=2, column=col, value=info["teacher"])
            row = 3
            for last, first in info["students"]:
                ws.cell(row=row, column=col, value=last)
                ws.cell(row=row, column=col + 1, value=first)
                expected.append(f"{first} {last}")
                row += 1
            # scheduling-note rows live INSIDE the roster columns and must
            # never be detected as students
            for note in CLASS_LIST_NOTE_ROWS:
                ws.cell(row=row, column=col, value=note)
                row += 1
            col += 2
    wb.save(path)
    return expected


def _build_support_3v(path: Path) -> list[str]:
    import openpyxl

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Sheet1"
    ws.append(["Student", "class", "Support notes", "Review date"])
    for name, class_code in SUPPORT_3V:
        ws.append([name, class_code, "Reading support", "2026-09-01"])
    wb.save(path)
    return [name for name, _ in SUPPORT_3V]


def _build_support_k5(path: Path) -> list[str]:
    import openpyxl

    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    expected: list[str] = []
    for class_code, info in SUPPORT_K5.items():
        ws = wb.create_sheet(title=class_code)
        ws.cell(row=1, column=1, value=class_code)
        row = 2
        for staff_name in info["staff"]:
            ws.cell(row=row, column=1, value=staff_name)
            ws.cell(row=row, column=2, value="support staff")
            row += 1
        ws.cell(row=row, column=1, value="Student")
        ws.cell(row=row, column=2, value="Accommodations in the classroom")
        ws.cell(row=row, column=3, value="Medical needs / allergies")
        row += 1
        for student in info["students"]:
            ws.cell(row=row, column=1, value=student)
            ws.cell(row=row, column=2, value="Extra time")
            ws.cell(row=row, column=3, value="None")
            expected.append(student)
            row += 1
    wb.save(path)
    return expected


def _build_zero_student(path: Path, rows: list[tuple[str, ...]], title: str) -> None:
    import openpyxl

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = title
    for row in rows:
        ws.append(list(row))
    wb.save(path)


